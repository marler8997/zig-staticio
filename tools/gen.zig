//! Generates src/std-<zig version>.patch for the zig building this tool
//! (`zig build update-patch`).
//!
//! The patch adds `std.Options.io_vtable` (default `.runtime`: unchanged std).
//! Selecting an implementation makes `std.Io` the added `IoStatic.zig`, a copy
//! of `Io.zig` whose `vtable` is a comptime namespace, so `io.vtable.X(...)` is
//! a direct call. Implementations get `vtable_fns` and skip building a vtable.
//! `Io.zig` is renamed to `IoRuntime.zig`, so importing it directly instead of
//! using `std.Io` is a compile error rather than a silent runtime vtable.
//!
//! Each transform checks the code looks as expected and fails otherwise.
//!
//! Usage: gen STD_DIR OUT_PATCH DEP_FILE
//!   DEP_FILE gets the files read from STD_DIR, for the build system.

const std = @import("std");

const vtable_fields = std.meta.fieldNames(std.Io.VTable);

/// Get `vtable_fns`, selected by `.threaded`. Uring, Kqueue and Dispatch don't
/// match `std.Io.VTable` in zig 0.17.0.
const implementations = [_][]const u8{"Io/Threaded.zig"};

fn fatal(comptime fmt: []const u8, args: anytype) noreturn {
    std.log.err(fmt, args);
    std.process.exit(0xff);
}

/// Replaces line aligned `src[start..end]` with whole lines `text`.
const Edit = struct {
    start: usize,
    end: usize,
    text: []const u8,
};

pub fn main(init: std.process.Init) !void {
    const io = init.io;
    const arena = init.arena.allocator();

    const args = try init.minimal.args.toSlice(arena);
    if (args.len != 4) fatal("usage: gen STD_DIR OUT_PATCH DEP_FILE", .{});
    const std_path = args[1];
    const out_path = args[2];
    const dep_path = args[3];
    const zig_version = @import("builtin").zig_version_string;

    var std_dir = std.Io.Dir.cwd().openDir(io, std_path, .{}) catch |err|
        fatal("open '{s}' failed with {t}", .{ std_path, err });
    defer std_dir.close(io);
    for ([_][]const u8{ "IoStatic.zig", "IoRuntime.zig" }) |added| {
        if (std_dir.statFile(io, added, .{})) |_| fatal("'{s}/{s}' already exists", .{ std_path, added }) else |err| switch (err) {
            error.FileNotFound => {},
            else => fatal("stat '{s}/{s}' failed with {t}", .{ std_path, added, err }),
        }
    }
    writeDepFile(io, arena, dep_path, std_path);

    const std_zig = readFile(io, arena, std_dir, std_path, "std.zig");
    const io_zig = readFile(io, arena, std_dir, std_path, "Io.zig");

    var patch: std.Io.Writer.Allocating = .init(arena);
    const w = &patch.writer;
    try w.print(
        \\staticio's patch of the zig {s} standard library, see https://github.com/marler8997/zig-staticio.
        \\Generated by tools/gen.zig (zig build update-patch), apply with patch.
        \\
        \\
    , .{zig_version});
    try writeFileDiff(w, "std.zig", null, std_zig, &stdZigEdits(std_zig));
    // copied before the rename, git reads both from the original Io.zig
    try writeFileDiff(w, "IoStatic.zig", "Io.zig", io_zig, &.{ioStaticEdit(io_zig)});
    try w.writeAll(
        \\diff --git a/Io.zig b/IoRuntime.zig
        \\similarity index 100%
        \\rename from Io.zig
        \\rename to IoRuntime.zig
        \\
    );
    for (implementations) |path| {
        const src = readFile(io, arena, std_dir, std_path, path);
        try writeFileDiff(w, path, null, src, &try implementationEdits(arena, src));
    }

    std.Io.Dir.cwd().writeFile(io, .{ .sub_path = out_path, .data = patch.written() }) catch |err|
        fatal("write '{s}' failed with {t}", .{ out_path, err });
}

fn readFile(io: std.Io, arena: std.mem.Allocator, dir: std.Io.Dir, dir_path: []const u8, sub_path: []const u8) []const u8 {
    const src = dir.readFileAlloc(io, sub_path, arena, .unlimited) catch |err|
        fatal("read '{s}/{s}' failed with {t}", .{ dir_path, sub_path, err });
    if (src.len == 0 or src[src.len - 1] != '\n') fatal("'{s}/{s}' doesn't end with a newline", .{ dir_path, sub_path });
    return src;
}

/// The files this tool reads from STD_DIR.
const read_files = [_][]const u8{ "std.zig", "Io.zig" } ++ implementations;

/// Writes a Makefile style dependency file of `read_files`, so the build
/// system tracks them by content.
fn writeDepFile(io: std.Io, arena: std.mem.Allocator, out_path: []const u8, std_path: []const u8) void {
    const std_abs = std.Io.Dir.cwd().realPathFileAlloc(io, std_path, arena) catch |err|
        fatal("resolve '{s}' failed with {t}", .{ std_path, err });
    const file = std.Io.Dir.cwd().createFile(io, out_path, .{}) catch |err|
        fatal("create '{s}' failed with {t}", .{ out_path, err });
    defer file.close(io);
    var buf: [4096]u8 = undefined;
    var writer = file.writer(io, &buf);
    writeDeps(&writer.interface, std_abs) catch |err| switch (err) {
        error.WriteFailed => fatal("write '{s}' failed with {t}", .{ out_path, writer.err.? }),
    };
}

fn writeDeps(w: *std.Io.Writer, std_abs: []const u8) error{WriteFailed}!void {
    try w.writeAll("deps:");
    for (read_files) |path| {
        try w.writeAll(" \\\n ");
        try writeDepPath(w, std_abs);
        try w.writeByte(std.fs.path.sep);
        // read_files use '/', fine on windows too
        try writeDepPath(w, path);
    }
    try w.writeAll("\n");
    try w.flush();
}

fn writeDepPath(w: *std.Io.Writer, path: []const u8) error{WriteFailed}!void {
    // zig's dependency file parser only unescapes spaces
    for (path) |c| {
        if (c == ' ') try w.writeByte('\\');
        try w.writeByte(c);
    }
}

/// Writes a git diff of `edits` applied to `src`, a copy of `copy_from` if set.
fn writeFileDiff(
    w: *std.Io.Writer,
    path: []const u8,
    copy_from: ?[]const u8,
    src: []const u8,
    edits: []const Edit,
) error{WriteFailed}!void {
    const from = copy_from orelse path;
    try w.print("diff --git a/{s} b/{s}\n", .{ from, path });
    if (copy_from) |source| try w.print("copy from {s}\ncopy to {s}\n", .{ source, path });
    try w.print("--- a/{s}\n+++ b/{s}\n", .{ from, path });

    for (edits, 0..) |edit, i| {
        if (edit.start > edit.end or (i > 0 and edits[i - 1].end > edit.start))
            fatal("{s}: edits must be in order and not overlap", .{path});
    }
    const context = 3;
    var line_delta: isize = 0;
    var i: usize = 0;
    while (i < edits.len) {
        // edits with overlapping context share a hunk
        var last = i;
        while (last + 1 < edits.len and
            lineOf(src, edits[last + 1].start) -| lineOf(src, edits[last].end) <= 2 * context) last += 1;
        const hunk_start = lineOf(src, edits[i].start) -| context;
        const hunk_end = @min(lineCount(src), lineOf(src, edits[last].end) + context);

        var old_count: usize = 0;
        var new_count: usize = 0;
        for (edits[i .. last + 1]) |edit| {
            old_count += lineOf(src, edit.end) - lineOf(src, edit.start);
            new_count += std.mem.count(u8, edit.text, "\n");
        }
        const context_count = (hunk_end - hunk_start) - old_count;
        old_count += context_count;
        new_count += context_count;
        try w.print("@@ -{f} +{f} @@\n", .{
            Range{ .start = hunk_start + 1, .count = old_count },
            Range{ .start = @intCast(@as(isize, @intCast(hunk_start + 1)) + line_delta), .count = new_count },
        });
        line_delta += @as(isize, @intCast(new_count)) - @as(isize, @intCast(old_count));

        var offset = lineStart(src, hunk_start);
        for (edits[i .. last + 1]) |edit| {
            try writeLines(w, ' ', src[offset..edit.start]);
            try writeLines(w, '-', src[edit.start..edit.end]);
            try writeLines(w, '+', edit.text);
            offset = edit.end;
        }
        try writeLines(w, ' ', src[offset..lineStart(src, hunk_end)]);
        i = last + 1;
    }
}

const Range = struct {
    start: usize,
    count: usize,
    pub fn format(r: Range, w: *std.Io.Writer) error{WriteFailed}!void {
        try w.print("{},{}", .{ r.start, r.count });
    }
};

fn writeLines(w: *std.Io.Writer, prefix: u8, lines: []const u8) error{WriteFailed}!void {
    var it = std.mem.splitScalar(u8, lines, '\n');
    while (it.next()) |line| {
        if (it.index == null and line.len == 0) break; // after the last newline
        try w.writeByte(prefix);
        try w.writeAll(line);
        try w.writeByte('\n');
    }
}

/// 0-based line of `offset`.
fn lineOf(src: []const u8, offset: usize) usize {
    return std.mem.count(u8, src[0..offset], "\n");
}

fn lineCount(src: []const u8) usize {
    return std.mem.count(u8, src, "\n");
}

/// Offset of 0-based `line`, `src.len` past the end.
fn lineStart(src: []const u8, line: usize) usize {
    var offset: usize = 0;
    for (0..line) |_| offset = (std.mem.indexOfScalarPos(u8, src, offset, '\n') orelse return src.len) + 1;
    return offset;
}

fn stdZigEdits(src: []const u8) [2]Edit {
    if (findIdentifier(src, "IoVtable")) |offset| fatal("std.zig already uses 'IoVtable' (offset {})", .{offset});
    const decl = "pub const Io = @import(\"Io.zig\");\n";
    const decl_index = indexOfOnce(src, "\n" ++ decl) + 1;
    const options = "pub const Options = struct {\n";
    const options_end = indexOfOnce(src, "\n" ++ options) + 1 + options.len;
    if (options_end < decl_index) fatal("expected std.Io to be declared before std.Options", .{});
    return .{
        .{ .start = decl_index, .end = decl_index + decl.len, .text =
        \\/// `IoRuntime.zig` (`Io.zig` renamed) if `options.io_vtable` is `.runtime`,
        \\/// otherwise `IoStatic.zig`. Patched by staticio.
        \\pub const Io = if (options.io_vtable == .runtime) @import("IoRuntime.zig") else @import("IoStatic.zig");
        \\/// See `Options.io_vtable`. Added by staticio.
        \\pub const IoVtable = union(enum) {
        \\    /// The normal runtime vtable.
        \\    runtime,
        \\    /// `std.Io.Threaded`.
        \\    threaded,
        \\    /// A namespace of `std.Io.VTable` functions, only reachable ones must exist.
        \\    custom: type,
        \\};
        \\
        },
        .{ .start = options_end, .end = options_end, .text =
        \\    /// Anything but `.runtime` makes `std.Io` calls direct, compiling only
        \\    /// reachable operations, and fixes the program to that implementation.
        \\    /// Added by staticio.
        \\    io_vtable: IoVtable = .runtime,
        \\
        \\
        },
    };
}

fn ioStaticEdit(src: []const u8) Edit {
    const field = "vtable: *const VTable,\n";
    const i = indexOfOnce(src, "\n" ++ field) + 1;
    return .{ .start = i, .end = i + field.len, .text =
    \\/// Selected by `std.options.io_vtable`; comptime, so `io.vtable.X` calls are
    \\/// direct. Patched by staticio.
    \\comptime vtable: type = switch (std.options.io_vtable) {
    \\    .runtime => unreachable,
    \\    .threaded => Threaded.vtable_fns,
    \\    .custom => |namespace| namespace,
    \\},
    \\
    };
}

/// Adds `vtable_fns` and makes `io()` skip the vtable when one is selected.
fn implementationEdits(arena: std.mem.Allocator, src: []const u8) ![2]Edit {
    if (findIdentifier(src, "vtable_fns")) |offset| fatal("'vtable_fns' already exists (offset {})", .{offset});

    // pub fn io(NAME: *TYPE) Io {
    const io_fn = indexOfOnce(src, "\npub fn io(") + 1;
    const param_start = io_fn + "pub fn io(".len;
    const param_end = std.mem.indexOfPos(u8, src, param_start, ": *") orelse fatal("unexpected 'pub fn io' signature", .{});
    const param = src[param_start..param_end];
    const type_start = param_end + ": *".len;
    const type_end = std.mem.indexOfPos(u8, src, type_start, ") Io {\n") orelse fatal("unexpected 'pub fn io' signature", .{});
    const container = src[type_start..type_end];
    const signature_end = type_end + ") Io {\n".len;
    for ([_][]const u8{ param, container }) |name| {
        for (name) |c| if (!isIdentChar(c)) fatal("unexpected 'pub fn io' signature", .{});
    }
    // must be the file's own type
    if (!hasSelfDecl(src, container)) fatal("expected 'const {s} = @This();'", .{container});

    const literal_marker = ".vtable = &.{";
    const literal_start = (std.mem.indexOfPos(u8, src, io_fn, literal_marker) orelse
        fatal("vtable literal not found in 'pub fn io'", .{})) + literal_marker.len;
    const literal = src[literal_start..matchingClose(src, literal_start)];

    var seen: std.enums.EnumSet(std.meta.FieldEnum(std.Io.VTable)) = .empty;
    var it: EntryIterator = .{ .src = literal };
    while (it.next()) |entry| {
        const field = std.meta.stringToEnum(std.meta.FieldEnum(std.Io.VTable), entry.name) orelse
            fatal("{s} vtable literal has unknown field '{s}'", .{ container, entry.name });
        if (seen.contains(field)) fatal("{s} vtable literal sets '{s}' twice", .{ container, entry.name });
        seen.insert(field);
    }
    if (seen.count() != vtable_fields.len) {
        var missing = seen.complement().iterator();
        while (missing.next()) |field| std.log.err("{s} vtable literal is missing '{t}'", .{ container, field });
        fatal("{s} vtable literal doesn't set every std.Io.VTable field", .{container});
    }

    var fns: std.Io.Writer.Allocating = .init(arena);
    const w = &fns.writer;
    try w.writeAll(
        \\/// `std.Io` operations for `std.Options.io_vtable`. Added by staticio.
        \\pub const vtable_fns = struct {
        \\
    );
    it = .{ .src = literal };
    while (it.next()) |entry| {
        try w.print("    pub const {s} = ", .{entry.name});
        // continuation lines move from the entry's indent to the decl's
        var lines = std.mem.splitScalar(u8, entry.value, '\n');
        try writeQualified(w, container, lines.first());
        while (lines.next()) |line| {
            const indent = entry.indent orelse
                fatal("{s} vtable entry '{s}' spans lines but doesn't start its line", .{ container, entry.name });
            if (indent < decl_indent or !std.mem.allEqual(u8, line[0..@min(line.len, indent - decl_indent)], ' '))
                fatal("{s} vtable entry '{s}' has a line indented less than the entry", .{ container, entry.name });
            try w.writeByte('\n');
            try writeQualified(w, container, line[@min(line.len, indent - decl_indent)..]);
        }
        try w.writeAll(";\n");
    }
    try w.writeAll("};\n\n");

    return .{
        .{ .start = io_fn, .end = io_fn, .text = fns.written() },
        .{ .start = signature_end, .end = signature_end, .text = try std.fmt.allocPrint(arena,
            \\    switch (std.options.io_vtable) {{
            \\        .runtime => {{}},
            \\        .threaded => return .{{ .userdata = {s} }},
            \\        // std's own Io, like the default `std.Options.debug_io`, would call
            \\        // the custom functions with a `*{s}` userdata
            \\        .custom => @compileError("std.Io.{s} used with a custom std_options.io_vtable, declare root.std_options_debug_io and don't take a std.process.Init in main"),
            \\    }}
            \\
        , .{ param, container, container }) },
    };
}

/// Writes `value` with vtable field names qualified as `container.name`, which
/// `vtable_fns` would otherwise shadow.
/// Column of the `pub const` decls in `vtable_fns`.
const decl_indent = 4;

fn writeQualified(w: *std.Io.Writer, container: []const u8, value: []const u8) error{WriteFailed}!void {
    var cursor: usize = 0;
    var i: usize = 0;
    while (i < value.len) {
        if (!isIdentChar(value[i]) or std.ascii.isDigit(value[i])) {
            i += 1;
            continue;
        }
        const start = i;
        while (i < value.len and isIdentChar(value[i])) i += 1;
        const after_dot = start > 0 and value[start - 1] == '.';
        if (!after_dot and isVTableField(value[start..i])) {
            try w.writeAll(value[cursor..start]);
            try w.writeAll(container);
            try w.writeAll(".");
            try w.writeAll(value[start..i]);
            cursor = i;
        }
    }
    try w.writeAll(value[cursor..]);
}

fn isVTableField(name: []const u8) bool {
    inline for (vtable_fields) |field| {
        if (std.mem.eql(u8, name, field)) return true;
    }
    return false;
}

const EntryIterator = struct {
    src: []const u8,
    index: usize = 0,

    const Entry = struct {
        name: []const u8,
        value: []const u8,
        /// Column of the entry's '.', null if it doesn't start its line.
        indent: ?usize,
    };

    /// Next `.name = value` of a struct literal body.
    fn next(it: *EntryIterator) ?Entry {
        it.index = skipSpaceAndComments(it.src, it.index);
        if (it.index == it.src.len) return null;
        if (it.src[it.index] != '.') fatal("expected '.' to start vtable entry, got '{s}'", .{snippet(it.src[it.index..])});
        const dot = it.index;
        const line_start = if (std.mem.lastIndexOfScalar(u8, it.src[0..dot], '\n')) |nl| nl + 1 else 0;
        const name_start = dot + 1;
        var name_end = name_start;
        while (name_end < it.src.len and isIdentChar(it.src[name_end])) name_end += 1;
        const eq = std.mem.indexOfPos(u8, it.src, name_end, "=") orelse fatal("vtable entry has no '='", .{});
        if (std.mem.trim(u8, it.src[name_end..eq], " ").len != 0)
            fatal("unexpected text before '=' in vtable entry '{s}'", .{it.src[name_start..name_end]});
        const value_start = eq + 1;
        const value_end = endOfValue(it.src, value_start);
        it.index = if (value_end < it.src.len) value_end + 1 else value_end;
        return .{
            .name = it.src[name_start..name_end],
            .value = std.mem.trim(u8, it.src[value_start..value_end], " \n"),
            .indent = if (std.mem.trimStart(u8, it.src[line_start..dot], " ").len == 0) dot - line_start else null,
        };
    }
};

/// Index of the ',' ending the value at `start`, or `src.len`.
fn endOfValue(src: []const u8, start: usize) usize {
    var depth: usize = 0;
    var i = start;
    while (i < src.len) : (i += 1) switch (src[i]) {
        '(', '[', '{' => depth += 1,
        ')', ']', '}' => depth -= 1,
        ',' => if (depth == 0) return i,
        '"', '\'' => i = endOfQuoted(src, i),
        '/' => if (i + 1 < src.len and src[i + 1] == '/') {
            i = std.mem.indexOfScalarPos(u8, src, i, '\n') orelse src.len;
        },
        else => {},
    };
    return src.len;
}

/// Index of the brace closing the one before `open`.
fn matchingClose(src: []const u8, open: usize) usize {
    var depth: usize = 1;
    var i = open;
    while (i < src.len) : (i += 1) switch (src[i]) {
        '(', '[', '{' => depth += 1,
        ')', ']', '}' => {
            depth -= 1;
            if (depth == 0) return i;
        },
        '"', '\'' => i = endOfQuoted(src, i),
        '/' => if (i + 1 < src.len and src[i + 1] == '/') {
            i = std.mem.indexOfScalarPos(u8, src, i, '\n') orelse src.len;
        },
        else => {},
    };
    fatal("unmatched brace at offset {}", .{open});
}

fn endOfQuoted(src: []const u8, open: usize) usize {
    const quote = src[open];
    var i = open + 1;
    while (i < src.len) : (i += 1) switch (src[i]) {
        '\\' => i += 1,
        else => if (src[i] == quote) return i,
    };
    fatal("unterminated quote at offset {}", .{open});
}

fn skipSpaceAndComments(src: []const u8, start: usize) usize {
    var i = start;
    while (i < src.len) {
        if (std.ascii.isWhitespace(src[i])) {
            i += 1;
        } else if (std.mem.startsWith(u8, src[i..], "//")) {
            i = std.mem.indexOfScalarPos(u8, src, i, '\n') orelse src.len;
        } else break;
    }
    return i;
}

fn isIdentChar(c: u8) bool {
    return std.ascii.isAlphanumeric(c) or c == '_';
}

fn hasSelfDecl(src: []const u8, name: []const u8) bool {
    const suffix = " = @This();\n";
    var start: usize = 0;
    while (std.mem.indexOfPos(u8, src, start, suffix)) |i| : (start = i + suffix.len) {
        const line_start = if (std.mem.lastIndexOfScalar(u8, src[0..i], '\n')) |nl| nl + 1 else 0;
        const line = src[line_start..i];
        if (std.mem.startsWith(u8, line, "const ") and std.mem.eql(u8, line["const ".len..], name)) return true;
    }
    return false;
}

fn findIdentifier(src: []const u8, name: []const u8) ?usize {
    var start: usize = 0;
    while (std.mem.indexOfPos(u8, src, start, name)) |i| {
        const end = i + name.len;
        const bounded_before = i == 0 or !isIdentChar(src[i - 1]);
        const bounded_after = end == src.len or !isIdentChar(src[end]);
        if (bounded_before and bounded_after) return i;
        start = end;
    }
    return null;
}

fn indexOfOnce(src: []const u8, needle: []const u8) usize {
    const i = std.mem.indexOf(u8, src, needle) orelse fatal("expected to find '{s}'", .{needle});
    if (std.mem.indexOfPos(u8, src, i + needle.len, needle)) |_| fatal("found '{s}' more than once", .{needle});
    return i;
}

fn snippet(s: []const u8) []const u8 {
    return s[0..@min(s.len, 40)];
}
